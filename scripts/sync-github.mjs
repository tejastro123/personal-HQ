/**
 * Build-time GitHub snapshot for Repo Pulse.
 * Public API only — no tokens. Rate limits are fine at deploy/build frequency.
 *
 * Usage: node scripts/sync-github.mjs
 * Writes: src/data/github-snapshot.generated.ts (imported by github-snapshot.ts if present)
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const USER = process.env.GITHUB_USER || "tejastro123";
const API = `https://api.github.com/users/${USER}/repos?per_page=100&sort=pushed`;

async function main() {
  const res = await fetch(API, {
    headers: {
      Accept: "application/vnd.github+json",
      "User-Agent": "personal-hq-snapshot",
    },
  });
  if (!res.ok) {
    console.error(`[sync-github] GitHub API ${res.status} — keeping project-derived snapshot`);
    process.exitCode = 1;
    return;
  }
  const repos = await res.json();
  const userRes = await fetch(`https://api.github.com/users/${USER}`, {
    headers: { Accept: "application/vnd.github+json", "User-Agent": "personal-hq-snapshot" },
  });
  const user = userRes.ok ? await userRes.json() : null;

  const payload = {
    syncedAt: new Date().toISOString(),
    source: "live-api",
    user: user
      ? {
          login: user.login,
          publicRepos: user.public_repos ?? 0,
          followers: user.followers ?? 0,
          htmlUrl: user.html_url,
        }
      : null,
    repos: (Array.isArray(repos) ? repos : []).map((r) => ({
      name: r.name,
      description: r.description ?? null,
      language: r.language ?? null,
      stargazersCount: r.stargazers_count ?? 0,
      forksCount: r.forks_count ?? 0,
      openIssuesCount: r.open_issues_count ?? 0,
      pushedAt: r.pushed_at ?? "",
      topics: r.topics ?? [],
      archived: Boolean(r.archived),
      fork: Boolean(r.fork),
      htmlUrl: r.html_url,
    })),
  };

  const outDir = join(ROOT, "src", "data");
  mkdirSync(outDir, { recursive: true });
  const outFile = join(outDir, "github-snapshot.generated.ts");
  writeFileSync(
    outFile,
    `// Generated by scripts/sync-github.mjs — do not hand-edit.\n` +
      `import type { GithubSnapshot } from "./github-snapshot";\n\n` +
      `export const generatedSnapshot: GithubSnapshot = ${JSON.stringify(payload, null, 2)};\n`,
    "utf8",
  );
  console.log(`[sync-github] wrote ${outFile} (${payload.repos.length} repos)`);
}

main().catch((err) => {
  console.error("[sync-github]", err);
  process.exitCode = 1;
});
